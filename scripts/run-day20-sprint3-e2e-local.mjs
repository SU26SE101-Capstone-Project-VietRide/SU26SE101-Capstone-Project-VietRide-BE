// Day-20 passenger journey.  Each child runner owns and verifies the cleanup of
// its deterministic fixtures; this orchestrator supplies the required dependency
// order and a redacted result for every journey component.
import { spawnSync } from 'node:child_process';
import crypto from 'node:crypto';

const root = process.cwd();
const gatewayBaseUrl = process.env.GATEWAY_BASE_URL || 'http://localhost:3000';
const passengerEmail = `day20-${crypto.randomUUID()}@local.test`;
const passengerPassword = 'Day20Journey!234';

function psql(sql) {
  const result = spawnSync('docker', [
    'exec', 'vietride_postgres', 'psql', '-v', 'ON_ERROR_STOP=1', '-U', 'vietride', '-d', 'vietride_identity', '-Atc', sql,
  ], { cwd: root, encoding: 'utf8' });
  if (result.error || result.status !== 0) throw new Error('Day-20 Identity fixture query failed.');
  return result.stdout.trim();
}

function cleanupPassenger(userId) {
  if (!userId) return;
  psql(`DELETE FROM vietride_identity.user_devices WHERE user_id = '${userId}';
DELETE FROM vietride_identity.oauth_identities WHERE user_id = '${userId}';
DELETE FROM vietride_identity.refresh_tokens WHERE user_id = '${userId}';
DELETE FROM vietride_identity.email_verification_tokens WHERE user_id = '${userId}';
DELETE FROM vietride_identity.users WHERE id = '${userId}';`);
  const count = psql(`SELECT count(*) FROM vietride_identity.users WHERE id = '${userId}';`);
  if (count !== '0') throw new Error(`Day-20 passenger fixture cleanup failed: users=${count}`);
}

async function jsonRequest(path, body) {
  const response = await fetch(`${gatewayBaseUrl}${path}`, {
    method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify(body),
  });
  const payload = await response.json().catch(() => undefined);
  if (!response.ok || payload?.success !== true)
    throw new Error(`Day-20 Gateway ${path} failed: HTTP ${response.status}.`);
  return payload.data;
}

async function registerAndLoginPassenger() {
  // All auth traffic goes through the Gateway. The local-only harness is used
  // solely to read the one-time code generated by the registration request.
  await jsonRequest('/v1/auth/register', {
    email: passengerEmail, password: passengerPassword, displayName: 'Day 20 Journey', phone: '+84901234567',
  });
  const otp = psql(`SELECT code FROM vietride_identity.email_verification_tokens evt
JOIN vietride_identity.users u ON u.id = evt.user_id
WHERE u.email = '${passengerEmail}' AND evt.purpose = 'REGISTRATION' ORDER BY evt.created_at DESC LIMIT 1`);
  if (!otp) throw new Error('Day-20 registration did not create a verification code.');
  await jsonRequest('/v1/auth/verify-email', { email: passengerEmail, code: otp, purpose: 'REGISTRATION' });
  const login = await jsonRequest('/v1/auth/login', { email: passengerEmail, password: passengerPassword });
  if (!login?.accessToken) throw new Error('Day-20 Gateway login did not return an access token.');
  const userId = psql(`SELECT id FROM vietride_identity.users WHERE email = '${passengerEmail}' LIMIT 1`);
  if (!userId) throw new Error('Day-20 registered passenger was not found.');
  console.log('PASS | Day20 Gateway passenger auth | register, verify, and login');
  return { userId, accessToken: login.accessToken };
}

async function refreshPassengerLogin(passenger) {
  const login = await jsonRequest('/v1/auth/login', { email: passengerEmail, password: passengerPassword });
  if (!login?.accessToken) throw new Error('Day-20 Gateway passenger re-login did not return an access token.');
  passenger.accessToken = login.accessToken;
  console.log('PASS | Day20 Gateway passenger auth refresh | login');
}

const journeyStages = [
  // A searchable, bookable real-seam trip must exist before a passenger can book.
  ['D11', 'scripts/run-day11-newman-local.js', 'trip generation, search, detail, and seat map'],
  // The local signed-IPN sandbox credit is the passenger journey top-up seam.
  ['D15', 'scripts/run-day15-newman-local.mjs', 'signed VNPay top-up, wallet credit, and replay'],
  // D16 retains the D11 fixture while it verifies both Wallet and VNPay booking
  // confirmation, then waits for the cancellation refund before cleanup.
  ['D16', 'scripts/run-day16-newman-local.mjs', 'Wallet/VNPay booking confirmation and cancellation refund'],
  ['D19', 'scripts/run-day19-newman-local.mjs', 'operator tenant monitor and denial'],
];

let failed = false;
let passenger;
try {
  passenger = await registerAndLoginPassenger();
  for (const [id, script, assertion] of journeyStages) {
  // D11/D16 may recreate Identity/Gateway containers. Re-login through Gateway
  // before each dependent child while retaining the same registered passenger.
  await refreshPassengerLogin(passenger);
  const result = spawnSync(process.execPath, [script], {
    cwd: root,
    env: {
      ...process.env,
      DAY20_PASSENGER_ID: passenger.userId,
      DAY20_PASSENGER_ACCESS_TOKEN: passenger.accessToken,
      DAY20_PASSENGER_EMAIL: passengerEmail,
      DAY20_PASSENGER_PASSWORD: passengerPassword,
    },
    shell: false,
    stdio: 'inherit',
  });
  const ok = !result.error && result.status === 0 && result.signal === null;
  if (ok) {
    console.log(`PASS | ${id} | ${assertion}`);
    continue;
  }

  failed = true;
  // Do not print child output, tokens, IDs, or process arguments here.  The child
  // already emits its redacted failure evidence and runs its finally cleanup.
  console.error(`FAIL | ${id} | ${assertion}`);
  break;
}
} catch (error) {
  failed = true;
  console.error(`FAIL | Day20 Gateway passenger journey | ${error.message}`);
} finally {
  try {
    cleanupPassenger(passenger?.userId);
    if (passenger?.userId) console.log('PASS | Day20 passenger fixture cleanup | temporary identity removed');
  } catch (cleanupError) {
    failed = true;
    console.error(`FAIL | Day20 passenger fixture cleanup | ${cleanupError.message}`);
  }
}

process.exitCode = failed ? 1 : 0;
